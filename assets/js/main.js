/* ============ B. BUILD CARDS & MODAL GALLERY ============ */
const pal=[['#5B8F5B','#2F6150','#F4C46A','#E7E1CF'],['#A6C58E','#86AF73','#D9733A','#EFE7D3'],['#8FB4DE','#5E86B8','#F4C46A','#E9E6DA'],['#2F6150','#1E4A40','#F4C46A','#DCE7C6']];
const motif=i=>{const[a,b,c,d]=pal[i%4];return `<svg viewBox="0 0 300 400" preserveAspectRatio="xMidYMid slice" aria-hidden="true"><rect width="300" height="400" fill="${d}"/><circle cx="215" cy="105" r="42" fill="${c}"/><path d="M50 400V215A75 75 0 0 1 125 140V400Z" fill="${a}"/><path d="M125 400V140A75 75 0 0 1 200 215V400Z" fill="${b}"/><circle cx="235" cy="352" r="55" fill="${a}"/><use href="#leaf" fill="${b}" transform="translate(235 300) rotate(20) scale(1.1)"/></svg>`};
const art=(p,i)=>`<div class="art">${p.img?`<img src="${p.img}" alt="${p.t}" loading="lazy" decoding="async" onload="this.classList.add('ok')" onerror="this.outerHTML=motif(${i})">`:motif(i)}</div>`;

const grid=document.querySelector('.grid'),tabs=document.querySelector('.tabs'),dlg=document.getElementById('dlg');

// 1. Render Cards to Grid
grid.innerHTML=projects.length?projects.map((p,i)=>`<button class="card" data-i="${i}" data-type="${p.type}">${art(p,i)}<h3>${p.t}</h3><small>${p.type}</small></button>`).join(''):`<div class="empty">${motif(0)}<p>New projects are on the way. Check back soon.</p></div>`;

// 2. Render Filter Tabs
['All',...new Set(projects.map(p=>p.type))].forEach((n,i)=>{
  const b=document.createElement('button');b.textContent=n;b.setAttribute('aria-pressed',i==0);
  b.onclick=()=>{tabs.querySelectorAll('button').forEach(x=>x.setAttribute('aria-pressed',x==b));
    grid.querySelectorAll('.card').forEach(c=>c.hidden=!(n=='All'||c.dataset.type==n))};
  tabs.append(b);
});

// 3. Open Modal with Gallery
grid.onclick = e => {
  const c = e.target.closest('.card');
  if (!c) return;
  const i = +c.dataset.i, p = projects[i];

  // 1. Normalize gallery items so each element preserves its own slide link if present
  const rawGallery = (p.gallery && p.gallery.length) ? p.gallery : (p.img ? [p.img] : []);
  const imgs = rawGallery.map(item => {
    if (typeof item === 'string') {
      return { src: item, d: p.d, link: null };
    }
    return { src: item.src, d: item.d || p.d, link: item.link || null };
  });

  let currentIndex = 0;

  // Build Dots & Arrows
  const dotsHTML = imgs.length > 1 
    ? `<div class="dlg-dots">${imgs.map((_, idx) => `<button class="dot ${idx === 0 ? 'active' : ''}" data-idx="${idx}" type="button"></button>`).join('')}</div>`
    : '';

  const navButtonsHTML = imgs.length > 1
    ? `<button class="nav-btn prev-btn" type="button">‹</button>
       <button class="nav-btn next-btn" type="button">›</button>`
    : '';

  const mainImageHTML = imgs.length 
    ? `<img id="dlg-main-img" src="${imgs[0].src}" alt="${p.t}">` 
    : motif(i);

  // Initial link state for slide 0
  const initialLinkHTML = imgs[0].link 
    ? `<a id="dlg-link-btn" class="btn btn-project" href="${imgs[0].link}" target="_blank" rel="noopener noreferrer">View project</a>`
    : `<a id="dlg-link-btn" class="btn btn-project" href="#" target="_blank" rel="noopener noreferrer" style="display:none;">View project</a>`;

  dlg.innerHTML = `
    <div class="dlg">
      <div class="dlg-media">
        <div class="dlg-art-frame">
          ${mainImageHTML}
          ${navButtonsHTML}
        </div>
        ${dotsHTML}
      </div>
      <div class="dlg-txt">
        <h3>${p.t}</h3>
        <p id="dlg-desc">${imgs[0] ? imgs[0].d : p.d}</p>
        <p class="dlg-tools"><strong>Tools:</strong> ${p.tools}</p>
        <div class="dlg-actions">
          ${initialLinkHTML}
          <button class="btn btn-close" type="button" onclick="dlg.close()">Close</button>
        </div>
      </div>
    </div>`;

  // Function to update slide, text, and button visibility dynamically
  const updateSlide = (newIndex) => {
    if (imgs.length <= 1) return;
    currentIndex = (newIndex + imgs.length) % imgs.length;

    const currentSlide = imgs[currentIndex];
    const mainImg = dlg.querySelector('#dlg-main-img');
    const descEl = dlg.querySelector('#dlg-desc');
    const linkBtn = dlg.querySelector('#dlg-link-btn');

    if (mainImg) mainImg.style.opacity = '0';
    if (descEl) descEl.style.opacity = '0';

    setTimeout(() => {
      if (mainImg) {
        mainImg.src = currentSlide.src;
        mainImg.style.opacity = '1';
      }
      if (descEl) {
        descEl.textContent = currentSlide.d;
        descEl.style.opacity = '1';
      }
      // Toggle button visibility based on whether current slide has a link
      if (linkBtn) {
        if (currentSlide.link) {
          linkBtn.href = currentSlide.link;
          linkBtn.style.display = 'inline-block';
        } else {
          linkBtn.style.display = 'none';
        }
      }
    }, 150);

    dlg.querySelectorAll('.dot').forEach((dot, idx) => {
      dot.classList.toggle('active', idx === currentIndex);
    });
  };

  // Event Listeners for Nav Arrows & Dots
  const prevBtn = dlg.querySelector('.prev-btn');
  const nextBtn = dlg.querySelector('.next-btn');
  const dotsContainer = dlg.querySelector('.dlg-dots');

  if (prevBtn) prevBtn.onclick = () => updateSlide(currentIndex - 1);
  if (nextBtn) nextBtn.onclick = () => updateSlide(currentIndex + 1);

  if (dotsContainer) {
    dotsContainer.onclick = (event) => {
      const dot = event.target.closest('.dot');
      if (dot) {
        updateSlide(+dot.dataset.idx);
      }
    };
  }

  dlg.showModal();
};
dlg.onclick = e => { if(e.target == dlg) dlg.close(); };

